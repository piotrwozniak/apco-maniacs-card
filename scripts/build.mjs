// Dependency-free HACS packaging. The standalone source still needs no build.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = name => readFile(new URL(name, root), 'utf8');
const {version} = JSON.parse(await read('package.json'));
const sources = await Promise.all(['weather.mjs', 'i18n.mjs', 'warun-card.js'].map(name => read(`warun-web/${name}`)));
const css = await read('warun-web/warun.css');
const code = sources.map(source => source.replace(/^import .*;\n/gm, '').replace(/^export /gm, '')).join('\n');
const cssDeclaration = /const CSS = new URL\([^\n]+;/;
if (!cssDeclaration.test(code)) throw new Error('Cannot find stylesheet reference');
const bundle = `// APCO Weather ${version} — generated by node scripts/build.mjs\n// Weather: Open-Meteo. Independent community project.\n(() => {\n${code.replace(cssDeclaration, `const CSS = ${JSON.stringify('data:text/css;charset=utf-8,' + encodeURIComponent(css))};`)}\n})();\n`;
if (/^import |^export /m.test(bundle)) throw new Error('Bundle still has module dependencies');
const outputs = ['dist/apco-maniacs-card.js','custom_components/apco_maniacs/frontend/apco-weather-card.js'].map(path=>new URL(path,root));
if (process.argv.includes('--check')) {
  for(const output of outputs)if (await readFile(output, 'utf8') !== bundle) throw new Error(`${output.pathname} is outdated; run npm run build`);
  console.log('HACS bundle is up to date');
} else {
  for(const output of outputs){await mkdir(new URL('.',output), {recursive:true});await writeFile(output,bundle);}
  console.log(`Built dist/apco-maniacs-card.js (${Buffer.byteLength(bundle)} bytes)`);
}
